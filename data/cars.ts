// Real inventory imported from the dealership's Instagram (@auto_lavce).
// Each car's photos live in public/cars/<igCode>/<n>.jpg.
function imgs(code: string, count: number): string[] {
  return Array.from({ length: count }, (_, i) => `/cars/${code}/${i + 1}.jpg`);
}

function describe(title: string, origin?: string): string {
  const intro = origin ? `${title}, увезен од ${origin}. ` : `${title}. `;
  return (
    intro +
    "Возилото е во добра состојба и подготвено за регистрација. " +
    "За цена и повеќе детали контактирајте нѐ или посетете нѐ во Auto Lavce, Битола."
  );
}

